CHAR_W = 5
CHAR_H = 7


def measure(text: str, spacing: int = 1, scale: int = 1) -> tuple[int, int]:
    text = text.upper()
    n = len(text)
    if n == 0:
        return (0, 0)
    w = (CHAR_W * n + spacing * (n - 1)) * scale
    h = CHAR_H * scale
    return (w, h)


def draw_text(pixels, text: str, x: int, y: int, color, spacing: int = 1, scale: int = 1, bounds=None) -> int:
    """bounds: optional (w, h) tuple for clipping; if omitted, no clipping."""
    text = text.upper()
    cx = x
    W = bounds[0] if bounds else None
    H = bounds[1] if bounds else None
    for ch in text:
        glyph = FONT_5X7.get(ch, FONT_5X7[' '])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == '1':
                    for dy in range(scale):
                        for dx in range(scale):
                            px = cx + gx * scale + dx
                            py = y + gy * scale + dy
                            if W is not None and (px < 0 or px >= W or py < 0 or py >= H):
                                continue
                            try:
                                pixels[px, py] = color
                            except IndexError:
                                pass
        cx += (CHAR_W + spacing) * scale
    return cx
